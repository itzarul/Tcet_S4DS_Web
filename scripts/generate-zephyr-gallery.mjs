// One-off generator: builds src/data/zephyrGallery.js from scraped Google Photos album HTML
// Usage: node scripts/generate-zephyr-gallery.mjs
import { readFileSync, writeFileSync } from 'fs';

const CACHE_DIR = 'scripts/.zephyr-cache';
const days = [
  { id: 'day1', label: 'Day 1', date: '25 Sept 2025', file: `${CACHE_DIR}/day1.ids`, album: 'https://photos.app.goo.gl/f4ppPuzMbfbhNNgf6' },
  { id: 'day2', label: 'Day 2', date: '26 Sept 2025', file: `${CACHE_DIR}/day2.ids`, album: 'https://photos.app.goo.gl/qeVpvrNGwhJcacHV6' },
  { id: 'day3', label: 'Day 3', date: '27 Sept 2025', file: `${CACHE_DIR}/day3.ids`, album: 'https://photos.app.goo.gl/RyQnpN1EVVXBWkPM8' },
];

const base = 'https://lh3.googleusercontent.com/';

const out = days.map((d) => {
  const ids = readFileSync(d.file, 'utf8')
    .split('\n')
    .map((l) => l.trim().replace(/^(https:\/\/)?lh3\.googleusercontent\.com\//, ''))
    .filter(Boolean);

  return { id: d.id, label: d.label, date: d.date, album: d.album, ids };
});

const banner = `// AUTO-GENERATED by scripts/generate-zephyr-gallery.mjs — do not edit by hand.
// Source: official Zephyr 2025 Google Photos albums (Day 1-3), scraped ${new Date().toISOString()}.
// Each id is a googleusercontent path; append =w####-h####-c for any size.
// Use zephyrPhotoUrl(id, w, h) from this file to build ready-to-use URLs.
`;

const js =
  banner +
  'export const zephyrGalleryDays = ' +
  JSON.stringify(out, null, 2) +
  `;

export function zephyrPhotoUrl(id, w = 640, h = 440) {
  return 'https://lh3.googleusercontent.com/' + id + '=w' + w + '-h' + h + '-c';
}
`;

writeFileSync('src/data/zephyrGallery.js', js);

console.log('Wrote src/data/zephyrGallery.js');
for (const d of out) console.log(`  ${d.label}: ${d.ids.length} photos`);
