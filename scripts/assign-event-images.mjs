// Classifies analyzed photos into scene types and assigns the best-fitting
// photo to each Zephyr event + hero banner. Output: src/data/zephyrEventImages.js
import { readFileSync, writeFileSync } from 'fs';

const feats = JSON.parse(readFileSync('scripts/.zephyr-cache/features.json', 'utf8')).filter((f) => !f.error);
const url = (id, w, h) => `https://lh3.googleusercontent.com/${id}=w${w}-h${h}-c`;

// ---------- 1. classify ----------
function classify(f) {
  const { skin, bright, sat, edges } = f;
  if (skin > 0.30 && edges < 0.13) return 'portrait';        // face fills frame
  if (bright < 0.34 && sat > 0.30) return 'neon';            // dark + vivid = UV/neon arena
  if (bright > 0.55 && edges > 0.10 && skin < 0.25) return 'stage'; // bright busy hall
  if (edges > 0.125 && skin > 0.10) return 'crowd';          // busy + people = event floor
  if (skin > 0.20) return 'people';                          // people-centric casual
  if (edges > 0.115) return 'action';                        // busy scene, few faces
  if (sat > 0.32) return 'colorful';
  return 'ambient';                                          // dull/empty wide shots
}

for (const f of feats) f.type = classify(f);

const counts = {};
feats.forEach((f) => (counts[f.type] = (counts[f.type] || 0) + 1));
console.log('Buckets:', counts);

// ---------- 2. event -> scene preference ----------
// score: higher = better fit; pick distinct photos per event
const PREF = {
  egaming: { neon: 5, ambient: 2, action: 2, colorful: 1 },
  technical: { stage: 4, action: 3, ambient: 2, colorful: 1 },
  workshop: { people: 4, crowd: 3, stage: 2, colorful: 1 },
  fun: { crowd: 5, action: 3, colorful: 2, neon: 2 },
  mini: { colorful: 4, crowd: 2, action: 2, people: 1 },
};
// extra hints for specific events
const HINTS = {
  'box-cricket': { stage: 3, action: 3 }, 'rink-football': { stage: 3, action: 3 },
  'tug-of-war': { crowd: 3, action: 3 }, 'arm-wrestling': { crowd: 3, people: 2 },
  'ctf': { ambient: 3, stage: 2 }, 'cad-competition': { ambient: 3 },
  'ideathon': { stage: 4, crowd: 2 }, 'valorant': { neon: 4 }, 'bgmi-classic': { neon: 4 },
  'neon-cricket': { neon: 5 }, 'neon-football': { neon: 5 }, 'neon-mania': { neon: 5 },
  'glow-carrom': { neon: 5 }, 'neon-dodgeball': { neon: 5 }, 'vintage-photobooth': { people: 4, colorful: 2 },
  'dance-workshop': { action: 3, colorful: 2 }, 'garba-workshop': { colorful: 3, action: 2 },
  'standup-comedy': { crowd: 4 }, 'haunted-house': { neon: 3, ambient: 2 },
};

const catOf = {};
const dataSrc = readFileSync('src/data/zephyr.js', 'utf8');
for (const m of dataSrc.matchAll(/\{\s*id:\s*"([a-z0-9-]+)",\s*name:\s*"[^"]*",\s*category:\s*"([a-z]+)"/g)) {
  catOf[m[1]] = m[2];
}
const eventIds = Object.keys(catOf);

// ---------- 3. greedy assignment ----------
function scorePhoto(f, type) {
  // base: prefer sharp, well-exposed, but not portraits for events
  let s = 0;
  s += Math.min(f.edges, 0.16) * 12;                 // busy = interesting
  s += (1 - Math.abs(f.bright - 0.45)) * 3;          // near p50 brightness
  s += f.sat * 4;                                    // vivid
  s += PREF[type][f.type] || 0;
  if (f.type === 'portrait') s -= 6;                 // avoid face closeups for events
  return s;
}

const used = new Set();
const assign = {};
const pool = [...feats];

for (const evId of eventIds) {
  const type = catOf[evId];
  const scored = pool
    .filter((f) => !used.has(f.day + '-' + f.idx))
    .map((f) => ({
      f,
      s: scorePhoto(f, type) + (HINTS[evId] ? (HINTS[evId][f.type] || 0) * 1.5 : 0),
    }))
    .sort((a, b) => b.s - a.s);
  if (scored.length) {
    const pick = scored[0];
    assign[evId] = pick.f;
    used.add(pick.f.day + '-' + pick.f.idx);
  }
}

// ---------- 4. hero banner: best wide dramatic non-portrait shot ----------
const bannerPool = feats
  .filter((f) => !used.has(f.day + '-' + f.idx) && f.type !== 'portrait')
  .sort((a, b) => (b.sat * 2 + Math.min(b.edges, 0.16) * 15 + (1 - Math.abs(b.bright - 0.5)) * 3) -
                  (a.sat * 2 + Math.min(a.edges, 0.16) * 15 + (1 - Math.abs(a.bright - 0.5)) * 3));
const banner = bannerPool[0];
if (banner) used.add(banner.day + '-' + banner.idx);

// ---------- 5. emit data file ----------
const banner2 = bannerPool[1]; // spare wide shot for events-page card
const out = {
  banner: banner ? { id: banner.id, day: banner.day, thumb: url(banner.id, 1280, 720), wide: url(banner.id, 1920) } : null,
  bannerAlt: banner2 ? { id: banner2.id, thumb: url(banner2.id, 900, 500) } : null,
  events: {},
};
for (const [evId, f] of Object.entries(assign)) {
  out.events[evId] = {
    id: f.id, day: f.day, type: f.type,
    thumb: url(f.id, 320, 240),
    medium: url(f.id, 640, 440),
    large: url(f.id, 1200),
  };
}

const bannerJs = `// AUTO-GENERATED by scripts/assign-event-images.mjs — smart scene-matched images.
// Each event got the best-fitting photo by perceptual class (neon/crowd/stage/...).
export const zephyrEventImages = ${JSON.stringify(out.events, null, 1)};

export const zephyrBanner = ${JSON.stringify(out.banner, null, 1)};

export const zephyrBannerAlt = ${JSON.stringify(out.bannerAlt, null, 1)};
`;
writeFileSync('src/data/zephyrEventImages.js', bannerJs);

console.log(`Assigned images to ${Object.keys(assign).length}/${eventIds.length} events + banner (day ${banner?.day} #${banner?.idx}, ${banner?.type})`);

// review sheet: chosen images grid
const cells = Object.entries(assign).map(([id, f]) =>
  `<figure><img src="${url(f.id, 200, 133)}" width="200" height="133"><figcaption>${id}<br>${f.type} d${f.day}#${f.idx}</figcaption></figure>`).join('');
writeFileSync('public/review-sheet.html', `<!doctype html><meta charset=utf-8><style>body{margin:0;background:#111;color:#eee;font:12px monospace}main{display:flex;flex-wrap:wrap;gap:6px;padding:8px}figure{margin:0}img{border-radius:4px;background:#222;display:block}figcaption{padding:2px 0}</style><h3 style="padding:0 10px">BANNER d${banner?.day}#${banner?.idx} (${banner?.type})</h3><img src="${url(banner.id, 400, 225)}"><main>${cells}</main>`);
console.log('Review sheet: /review-sheet.html');
