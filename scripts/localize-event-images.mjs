// Downloads the assigned event images + banner locally so /zephyr is fully
// self-hosted (no googleusercontent dependency for event thumbnails).
// Rewrites src/data/zephyrEventImages.js to point at /zephyr/events/<id>.jpg
import { mkdirSync, writeFileSync, readFileSync, existsSync } from 'fs';

const feats = JSON.parse(readFileSync('scripts/.zephyr-cache/features.json', 'utf8'));
const byId = new Map(feats.map((f) => [f.day + '-' + f.idx, f]));

mkdirSync('public/zephyr/events', { recursive: true });

async function dl(id, w, h, out) {
  if (existsSync(out)) return true;
  const res = await fetch(`https://lh3.googleusercontent.com/${id}=w${w}-h${h}-c`);
  if (!res.ok) throw new Error('HTTP ' + res.status);
  const buf = Buffer.from(await res.arrayBuffer());
  writeFileSync(out, buf);
  return true;
}

// parse generated file (v2 shape: thumb/medium/large + optional wide)
const genSrc = readFileSync('src/data/zephyrEventImages.js', 'utf8');
const eventsJson = JSON.parse(genSrc.match(/export const zephyrEventImages = ([\s\S]*?);\n\nexport const zephyrBanner/s)[1]);
const bannerJson = JSON.parse(genSrc.match(/export const zephyrBanner = ([\s\S]*?);\n/s)[1]);

const outEvents = {};
let n = 0;
const entries = Object.entries(eventsJson);
const BATCH = 8;
for (let i = 0; i < entries.length; i += BATCH) {
  await Promise.all(entries.slice(i, i + BATCH).map(async ([evId, img]) => {
    const f = byId.get(img.day + '-' + (img.id ? '' : '')); // not used; keep simple
    const path = `public/zephyr/events/${evId}.jpg`;
    try {
      if (!existsSync(path)) {
        await dl(img.id, 800, 550, path);
        n++;
      }
      outEvents[evId] = { src: `/zephyr/events/${evId}.jpg`, type: img.type, day: img.day };
    } catch (e) {
      console.error(`✗ ${evId}: ${e}`);
      outEvents[evId] = null;
    }
  }));
}

// banner (wide)
let bannerOut = null;
if (bannerJson) {
  try {
    if (!existsSync('public/zephyr/hero-backdrop.jpg')) {
      await dl(bannerJson.id, 1600, 900, 'public/zephyr/hero-backdrop.jpg');
    }
    bannerOut = { src: '/zephyr/hero-backdrop.jpg', type: bannerJson.type || 'crowd', day: bannerJson.day };
    n++;
  } catch (e) { console.error('✗ banner: ' + e); }
}

// emit new data file (local paths only)
const js = `// AUTO-GENERATED by scripts/localize-event-images.mjs
// Event images are self-hosted in public/zephyr/events/ (scene-matched).
export const zephyrEventImages = ${JSON.stringify(outEvents, null, 1)};

export const zephyrBanner = ${JSON.stringify(bannerOut, null, 1)};
`;
writeFileSync('src/data/zephyrEventImages.js', js);
console.log(`\nLocalized ${n}/${entries.length + 1} images. Data file rewritten to local paths.`);
